import {mkdir} from 'node:fs/promises';
import {expect,test} from '@playwright/test';
test('계정 없이 게스트로 로그인하고 기록·사진·개인 설정을 사용한 뒤 로그아웃한다',async({page},info)=>{
 test.setTimeout(90000);
 await page.addInitScript(()=>localStorage.setItem('yeoun_2:onboarding:v1',JSON.stringify({version:1,completed:true})));
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await mkdir('test-results-server/screenshots',{recursive:true});
 await page.goto('/login?next=/?personal=1');
 await expect(page.getByRole('link',{name:'ChatGPT로 계속'})).toHaveAttribute('href',/\/signin-with-chatgpt/);
 await expect(page.getByText(/7일간 유지/)).toBeVisible();
 await page.screenshot({path:`test-results-server/screenshots/guest-login-${info.project.name}.png`,animations:'disabled'});
 await page.getByRole('button',{name:'게스트로 시작',exact:true}).click();
 await expect(page.locator('.guest-session-label')).toHaveText('게스트');
 const personal=page.getByRole('dialog',{name:'마이페이지'});await expect(personal).toBeVisible();
 await expect(personal.getByRole('heading',{name:'게스트 여행자의 기억 보관함'})).toBeVisible();
 await personal.getByText('감정 메뉴 설정',{exact:true}).click();
 const settings=personal.locator('.emotion-menu-settings');await settings.getByRole('checkbox',{name:'슬픔',exact:true}).uncheck();
 await settings.getByRole('button',{name:'감정 메뉴 저장',exact:true}).click();await expect(settings.getByRole('status')).toContainText('저장했어요');
 await page.getByRole('button',{name:'지도',exact:true}).click();
 await page.getByRole('button',{name:'기억을 남길 장소 선택하기'}).click();
 await page.getByRole('button',{name:'이 위치 선택',exact:true}).click();
 const form=page.locator('.create-sheet');await expect(form).toBeVisible();
 await form.locator('#memory-title').fill('게스트로 남긴 오늘의 기록');
 await form.locator('#memory-content').fill('지나던 길에 잠깐 멈춰 하늘을 올려다보았다. 잠깐의 여유를 이곳에 남긴다.');
 await form.locator('input[type="file"]').setInputFiles('tests/fixtures/memory-photo.png');
 await form.getByRole('button',{name:'기억 남기기',exact:true}).click();
 const detail=page.getByRole('dialog',{name:'기억 상세'});await expect(detail.getByRole('heading',{name:'게스트로 남긴 오늘의 기록'})).toBeVisible();
 await expect(detail.getByRole('img',{name:'게스트로 남긴 오늘의 기록의 기억 사진 1'})).toBeVisible();
 await page.screenshot({path:`test-results-server/screenshots/guest-memory-${info.project.name}.png`,animations:'disabled'});
 // Read the resulting same-origin media URL to identify the disposable memory.
 const source=await detail.getByRole('img',{name:'게스트로 남긴 오늘의 기록의 기억 사진 1'}).getAttribute('src');expect(source).toMatch(/api\/media/);
 page.once('dialog',dialog=>dialog.accept());await detail.getByRole('button',{name:'삭제',exact:true}).click();await expect(detail).toHaveCount(0);
 await page.reload();await expect(page.locator('.guest-session-label')).toHaveText('게스트');
 await expect(personal.getByRole('heading',{name:'게스트 여행자의 기억 보관함'})).toBeVisible();
 await page.screenshot({path:`test-results-server/screenshots/guest-space-${info.project.name}.png`,animations:'disabled'});
 const signedOut=page.waitForNavigation({waitUntil:'load'});
 await page.getByRole('button',{name:'게스트 로그아웃',exact:true}).click();
 await signedOut;await expect(page.locator('.app-nav a[href="/login"]')).toBeAttached();
 await expect(page.locator('.raster-memory-marker').first()).toBeVisible();
 await expect(page.locator('.guest-session-label')).toHaveCount(0);await expect(personal).toHaveCount(0);
 await page.getByRole('button',{name:'내 기억',exact:true}).click();
 await expect(page.getByRole('link',{name:'로그인하고 기억 모으기'})).toBeVisible();
 expect(errors).toEqual([]);
});
